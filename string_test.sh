#!/bin/bash

str="Hello_World_2026"

echo "截取前五个字符:${str:0:5}"
echo "从第六个字符取到最后:${str:6}"

echo "将下划线替换成横线:${str//_/-}" # ${变量名//旧字符/新字符}，//表示全局替换

file="/var/log/nginx/access.log"
echo "只保留文件名:${file##*/}"  # ${变量##*/} 表示从左边开始，删除最后一个/及其左边的所有内容（掐头）
echo "只保留目录名:${file%/*}"  # ${变量%/*} 表示从右边开始，删除第一个/及其右边的所有内容（去尾）

echo "转大写：${str^^}"                           # ^^ 将字符串全部转为大写
echo "转小写：${str,,}"                           # ,, 将字符串全部转为小写
