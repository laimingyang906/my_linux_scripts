#!/bin/bash

# 定义一个数组（用空格分隔元素）
servers=("192.168.1.1" "10.0.0.1" "8.8.8.8" "39.106.44.177")

# 获取数组的长度
echo "服务器总数量：${#servers[@]}"              # ${#数组名[@]} 获取数组元素个数

# 遍历数组（必须加双引号和[@]）
for ip in "${servers[@]}"; do                    # "${数组名[@]}" 表示数组的所有元素，加引号防止元素中含空格被拆分
    echo "正在巡检服务器：$ip"
done

# 通过索引取值
echo "第一台服务器是：${servers[0]}"              # 数组索引从0开始
echo "最后一台服务器是：${servers[-1]}"            # -1代表最后一个元素
